function test_chasi_dynamic_online_wmmse
% One deterministic miniature trajectory; not a formal mobile acceptance run.
addpath(fullfile(fileparts(fileparts(mfilename('fullpath'))),'matlab','chasi'));
cfg=struct('users',1,'trps',1,'rank',1,'seed',79,'ttiMs',1,...
    'scsHz',30000,'speedKmh',0,'frequencyGhz',3.5,...
    'csiRsPeriodTti',40,'srsPeriodTti',340,'srsHops',17,...
    'srsHopIntervalTti',20,'pilotSnrDb',0,'csiRsSnrDb',0,...
    'srsRxRows',[1 2],'powerWattPerTrp',2,'serviceTrps',1,...
    'rbTotal',273,'trafficModel','legacy_bursts','trafficLoad',.3,...
    'outerIterations',2,'outerRelTol',1e-4,'outerPrecoderRelTol',5e-3,...
    'admmIterations',12,'cgIterations',8,'epsAbs',1e-5,'epsRel',1e-4,...
    'pfRateFloorBitsPerSHz',.01,'initializationMode','svd',...
    'initializationSeed',0);
h=complex(zeros(1,1,4,64)); h(1,1,1,1)=1; h(1,1,2,2)=.5;
resource=struct('H_true',h,'H',h,'C',repmat(reshape(eye(4)*.02,1,1,4,4),1,1,1,1),...
    'C_stat',repmat(reshape(eye(4)*.02,1,1,4,4),1,1,1,1),...
    'ueIds',1,'servingMask',true,'prior_gain',1,'rb_count',273,...
    'tx_rb_count',273,'resourceWeightNu',1);
scene=struct('config',cfg,'resources',resource,'active_prb_ratio',1,...
    'ue_xy',[0 0],'trp_xy',[0 0],'home',1);
w=complex(zeros(1,1,64,1)); w(1,1,1,1)=1;
solution=struct('precoder',{{w}},'branch','matrix_statistical');
traffic=struct('busy',false(1,340),'tail',false(1,340),...
    'terminal',false(1,340));
options=struct('windowTti',340,'offeredMbps',.1,...
    'fastPeriodTti',320,'slowPeriodTti',340,'beamPolicy','online_wmmse');
replay=chasi_time_evolution(scene,solution,options,traffic);
frozenOptions=options; frozenOptions.beamPolicy='frozen';
frozen=chasi_time_evolution(scene,solution,frozenOptions,traffic);
assert(replay.online_wmmse_updates==1);
assert(replay.events(17).online_wmmse_update);
assert(replay.max_power_violation_watt<1e-8);
assert(replay.events(17).online_wmmse_precoder_change>1e-8);
assert(abs(replay.physical_sum_bits_per_s_hz_time_mean-...
    frozen.physical_sum_bits_per_s_hz_time_mean)>1e-8);
fprintf('PASS miniature online WMMSE update, stop=%s\n',...
    replay.events(17).online_wmmse_reason);
end
