function comparisonTable=cf_print_result(result,label)
if nargin<2, label='Cell-Free result'; end
metric={'SumRate';'MeanRate';'MinRate';'Rate5';'Rate10'; ...
    'MeanExperienceRate';'EdgeExperienceRate5';'Jain'; ...
    'ActiveLinks';'TotalPower';'ActiveStreams'};
baseline=[result.baseline.SumRate;result.baseline.MeanRate;result.baseline.MinRate; ...
    result.baseline.Rate5;result.baseline.Rate10; ...
    result.baseline.ExperienceRate.MeanExperienceRate; ...
    result.baseline.ExperienceRate.EdgeExperienceRate5;result.baseline.Jain; ...
    result.baseline.ActiveLinks;result.baseline.TotalPower;sum(result.baseline.r(:))];
proposed=[result.SumRate;result.MeanRate;result.MinRate;result.Rate5;result.Rate10; ...
    result.ExperienceRate.MeanExperienceRate;result.ExperienceRate.EdgeExperienceRate5; ...
    result.Jain;result.ActiveLinks;result.TotalPower;result.ActiveStreams];
change=proposed-baseline; changePercent=100*change./(abs(baseline)+eps);
comparisonTable=table(metric,baseline,proposed,change,changePercent, ...
    'VariableNames',{'Metric','Baseline','Proposed','Change','ChangePercent'});
fprintf('\n================ %s ================\n',label);
fprintf('Objective J_true = %.6f, evaluation score = %.6f\n', ...
    result.Objective,result.Score);
disp(result.Candidate); disp(comparisonTable);
if isfield(result,'TrueChannel') && result.TrueChannel.Available
    fprintf('True-channel objective = %.6f, true edge experience p5 = %.6f\n', ...
        result.TrueChannel.SumRate,result.TrueChannel.ExperienceRate.EdgeExperienceRate5);
end
end
