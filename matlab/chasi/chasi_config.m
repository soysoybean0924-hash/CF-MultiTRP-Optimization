function cfg=chasi_config(overrides)
%CHASI_CONFIG Native MATLAB contract for the formal CHASI scene.
% Names and defaults follow chasi_formal_implementation/config.py. MATLAB
% indices (notably srsRxRows and rbGroups.start) are one-based.
if nargin<1, overrides=struct(); end
cfg=struct( ...
    'usersPerCell',10,'seed',20261011,'rank',2,...
    'solver','matrix_statistical','outerIterations',2,...
    'admmIterations',12,'cgIterations',8,...
    'powerWattPerTrp',20,'noiseWattPerRb',1e-10,...
    'pilotSnrDb',-10,'srsMode','awgn_independent',...
    'srsPilotSequences',8,'csiRsSnrDb',-3,'srsRxRows',[1 2],...
    'ageCoherenceMs',120,'prbUtilization',0.40,...
    'scheduleMode','legacy_random_full_groups',...
    'trafficLoad',0.30,'trafficModel','legacy_bursts',...
    'timeEvolutionTti',0,'offeredMbps',5,'fastPeriodTti',40,...
    'slowPeriodTti',340,...
    'usersPerActiveCellRb',0,'speedKmh',3,...
    'durationTti',340,'decisionTti',340,'ttiMs',1,...
    'serviceTrps',2,'frequencyGhz',3.5,...
    'channelMode','geometry_correlated_surrogate',...
    'maxInterferenceDistanceM',750,...
    'epsAbs',1e-5,'epsRel',1e-4,'outerRelTol',1e-4,...
    'outerPrecoderRelTol',5e-3,'pfRateFloorBitsPerSHz',1e-2,...
    'initializationMode','svd','initializationSeed',0,...
    'sites',7,'sectorsPerSite',3,'trps',21,'txPorts',64,...
    'ueRxPorts',4,'ueTxPorts',2,'rbTotal',273,...
    'bandwidthHz',100e6,'scsHz',30e3,...
    'srsPeriodTti',340,'srsHops',17,'csiRsPeriodTti',40,...
    'branches',{{'ideal','matrix_nominal','matrix_statistical','no_cooperation'}},...
    'outputDir','');
names=fieldnames(overrides);
for j=1:numel(names)
    name=names{j};
    if ~isfield(cfg,name)
        error('chasi_config:UnknownField','Unknown option %s',name);
    end
    cfg.(name)=overrides.(name);
end
if cfg.usersPerActiveCellRb==0
    cfg.usersPerActiveCellRb=ceil(cfg.usersPerCell/5);
end
cfg.users=cfg.trps*cfg.usersPerCell;
counts=[repmat(16,1,16),17];
starts=cumsum([1,counts(1:end-1)]);
cfg.rbGroups=struct('start',num2cell(starts),'count',num2cell(counts));
if ~ismember(cfg.usersPerCell,[10 15 20])
    error('chasi_config:InvalidUsersPerCell','usersPerCell must be 10, 15 or 20');
end
if cfg.rank<1 || cfg.rank>min(cfg.txPorts,cfg.ueRxPorts) || cfg.rank~=floor(cfg.rank)
    error('chasi_config:InvalidRank','rank must be an integer in 1..min(Tx,Rx)');
end
if cfg.trps~=cfg.sites*cfg.sectorsPerSite || cfg.rbTotal~=sum(counts)
    error('chasi_config:InvalidTopology','TRP or RB dimensions are inconsistent');
end
if cfg.prbUtilization<0.30 || cfg.prbUtilization>0.50
    error('chasi_config:InvalidUtilization','prbUtilization must be in [0.30,0.50]');
end
if ~ismember(string(cfg.scheduleMode),["legacy_random_full_groups","precise_shared_rb"])
    error('chasi_config:InvalidSchedule','Unknown scheduleMode');
end
if ~ismember(string(cfg.srsMode),["awgn_independent","pilot_reuse_gaussian"])
    error('chasi_config:InvalidSRS','Unknown srsMode');
end
if ~ismember(string(cfg.channelMode),["geometry_correlated_surrogate","umi_pathloss_subset","uma_pathloss_subset"])
    error('chasi_config:InvalidChannel','Unknown channelMode');
end
if ~ismember(string(cfg.trafficModel),["legacy_bursts","target_busy_fraction"])
    error('chasi_config:InvalidTraffic','Unknown trafficModel');
end
if ~ismember(string(cfg.initializationMode),["svd","home_biased","jittered"])
    error('chasi_config:InvalidInitialization','Unknown initializationMode');
end
if numel(cfg.srsRxRows)~=cfg.ueTxPorts || numel(unique(cfg.srsRxRows))~=cfg.ueTxPorts || ...
        any(cfg.srsRxRows<1) || any(cfg.srsRxRows>cfg.ueRxPorts)
    error('chasi_config:InvalidSRSPorts','srsRxRows must map two unique MATLAB Rx rows');
end
if cfg.durationTti<cfg.srsPeriodTti || cfg.decisionTti<0 || cfg.decisionTti>cfg.durationTti
    error('chasi_config:InvalidTime','Invalid duration or decision TTI');
end
if cfg.serviceTrps<1 || cfg.serviceTrps>cfg.trps || ...
        cfg.usersPerActiveCellRb<1 || cfg.usersPerActiveCellRb>floor(cfg.txPorts/cfg.rank)
    error('chasi_config:InvalidResource','Invalid service or MU count');
end
if cfg.epsAbs<=0 || cfg.epsRel<=0 || cfg.outerRelTol<=0 || ...
        cfg.outerPrecoderRelTol<=0 || cfg.pfRateFloorBitsPerSHz<=0
    error('chasi_config:InvalidTolerance','Tolerances and PF floor must be positive');
end
if cfg.srsPilotSequences<1 || cfg.srsPilotSequences>cfg.users || ...
        cfg.trafficLoad<=0 || cfg.trafficLoad>=1
    error('chasi_config:InvalidMeasurement','Invalid pilot count or traffic load');
end
if cfg.timeEvolutionTti<0 || cfg.offeredMbps<=0 || ...
        cfg.fastPeriodTti<1 || cfg.slowPeriodTti<1
    error('chasi_config:InvalidReplay','Invalid time evolution parameters');
end
end
