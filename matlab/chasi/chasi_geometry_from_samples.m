function [trp,ue,home,topology]=chasi_geometry_from_samples(cfg,angleUniform,radiusUniform)
%CHASI_GEOMETRY_FROM_SAMPLES Pure topology map from explicit uniform draws.
% Each draw array is [usersPerCell,TRP], with columns in TRP order.
expected=[cfg.usersPerCell,cfg.trps];
if ~isequal(size(angleUniform),expected) || ...
        ~isequal(size(radiusUniform),expected) || ...
        any(~isfinite(angleUniform(:))) || any(~isfinite(radiusUniform(:))) || ...
        any(angleUniform(:)<0 | angleUniform(:)>1) || ...
        any(radiusUniform(:)<0 | radiusUniform(:)>1)
    error('CHASI:GeometrySamples','Expected finite [usersPerCell,TRP] uniforms in [0,1]');
end
site=[450 450];
angles=(0:5)'*pi/3;
site=[site;site+cfg.siteSpacingM*[cos(angles) sin(angles)]];
trp=repelem(site,cfg.sectorsPerSite,1);
home=repelem((1:cfg.trps)',cfg.usersPerCell);
ue=zeros(cfg.users,2);
topology=struct('site_xy',site,...
    'trp_site_id',repelem((1:cfg.sites)',cfg.sectorsPerSite),...
    'trp_sector_id',repmat((1:cfg.sectorsPerSite)',cfg.sites,1),...
    'trp_cell_id',(1:cfg.trps)',...
    'trp_azimuth_deg',repmat((0:cfg.sectorsPerSite-1)'*...
        360/cfg.sectorsPerSite,cfg.sites,1),...
    'cell_inner_radius_m',cfg.ueInnerRadiusM,...
    'cell_outer_radius_m',cfg.cellOuterRadiusM,...
    'cell_half_width_deg',180/cfg.sectorsPerSite,...
    'ue_spatial_sampling',cfg.ueSpatialSampling,...
    'boundary_status','project modeling assumption; not specified by acceptance image');
for l=1:cfg.trps
    azimuthRad=mod(l-1,cfg.sectorsPerSite)*2*pi/cfg.sectorsPerSite+...
        (angleUniform(:,l)-0.5)*2*pi/cfg.sectorsPerSite;
    if strcmp(cfg.ueSpatialSampling,'legacy_sqrt_radius')
        radius=cfg.ueInnerRadiusM+...
            (cfg.cellOuterRadiusM-cfg.ueInnerRadiusM)*sqrt(radiusUniform(:,l));
    else
        radius=sqrt(cfg.ueInnerRadiusM^2+...
            (cfg.cellOuterRadiusM^2-cfg.ueInnerRadiusM^2)*radiusUniform(:,l));
    end
    idx=(l-1)*cfg.usersPerCell+(1:cfg.usersPerCell);
    ue(idx,:)=trp(l,:)+radius.*[cos(azimuthRad) sin(azimuthRad)];
end
end
