def txt(slide,x,y,w,h,text,size=19,color=NAVY,bold=False,align=PP_ALIGN.LEFT,
        fill=None,margin=.05,outline=None):
    sh=slide.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h))
    if fill:
        sh.fill.solid(); sh.fill.fore_color.rgb=fill
    if outline:
        sh.line.color.rgb=outline
    tf=sh.text_frame; tf.clear(); tf.word_wrap=True
    tf.margin_left=tf.margin_right=Inches(margin)
    tf.margin_top=tf.margin_bottom=Inches(margin)
    tf.vertical_anchor=MSO_ANCHOR.MIDDLE
    for idx,line in enumerate(text.split('\n')):
        p=tf.paragraphs[0] if idx==0 else tf.add_paragraph()
        p.text=line; p.alignment=align
        p.space_before=Pt(0); p.space_after=Pt(0)
        for r in p.runs:
            r.font.name=FONT; r.font.size=Pt(size); r.font.bold=bold; r.font.color.rgb=color
    return sh

def box(slide,x,y,w,h,fill=WHITE,edge=BORDER,radius=True):
    typ=MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE
    s=slide.shapes.add_shape(typ,Inches(x),Inches(y),Inches(w),Inches(h))
    s.fill.solid(); s.fill.fore_color.rgb=fill; s.line.color.rgb=edge
    return s

def line(slide,x1,y1,x2,y2,color=BLUE,width=2.0,dash=None):
    s=slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2))
    s.line.color.rgb=color; s.line.width=Pt(width)
    if dash: s.line.dash_style=dash
    return s

